function loadState() {
  try {
    const raw = localStorage.getItem(STORAGE_KEY) || localStorage.getItem(LEGACY_STORAGE_KEY);
    return raw ? migrateState(JSON.parse(raw)) : structuredClone(defaultState);
  } catch {
    return structuredClone(defaultState);
  }
}

function migrateState(rawState) {
  const migrated = { ...structuredClone(defaultState), ...(rawState || {}) };
  migrated.inspections = Array.isArray(rawState?.inspections) ? rawState.inspections.map((inspection) => ({
    documents: [], trainingRecords: [], closure: null, status: "draft", ...inspection,
  })) : [];
  migrated.issues = Array.isArray(rawState?.issues) ? rawState.issues.map((issue) => ({
    evidence: [], verificationCompleted: false, reinspectionStatus: "נדרש אימות בשטח", ...issue,
  })) : [];
  migrated.auditLog = Array.isArray(rawState?.auditLog) ? rawState.auditLog : [];
  migrated.schemaVersion = STATE_SCHEMA_VERSION;
  return migrated;
}

function openDatabase() {
  if (databasePromise) return databasePromise;
  databasePromise = new Promise((resolve, reject) => {
    const request = indexedDB.open(DATABASE_NAME, DATABASE_VERSION);
    request.onupgradeneeded = () => {
      if (!request.result.objectStoreNames.contains(STATE_STORE_NAME)) {
        request.result.createObjectStore(STATE_STORE_NAME, { keyPath: "id" });
      }
    };
    request.onsuccess = () => resolve(request.result);
    request.onerror = () => reject(request.error);
  });
  return databasePromise;
}

async function readStateFromDatabase() {
  const database = await openDatabase();
  return new Promise((resolve, reject) => {
    const transaction = database.transaction(STATE_STORE_NAME, "readonly");
    const request = transaction.objectStore(STATE_STORE_NAME).get(STATE_RECORD_ID);
    request.onsuccess = () => resolve(request.result?.value || null);
    request.onerror = () => reject(request.error);
  });
}

async function persistStateToDatabase(snapshot) {
  try {
    const database = await openDatabase();
    await new Promise((resolve, reject) => {
      const transaction = database.transaction(STATE_STORE_NAME, "readwrite");
      transaction.objectStore(STATE_STORE_NAME).put({ id: STATE_RECORD_ID, value: snapshot, updatedAt: new Date().toISOString() });
      transaction.oncomplete = resolve;
      transaction.onerror = () => reject(transaction.error);
    });
  } catch {
    // The app keeps a localStorage fallback for browsers that block IndexedDB.
  }
}

async function hydrateStateFromDatabase() {
  try {
    const stored = await readStateFromDatabase();
    if (stored) {
      state = migrateState(stored);
      return;
    }
    await persistStateToDatabase(structuredClone(state));
  } catch {
    renderSystemStatus("IndexedDB אינו זמין בדפדפן זה; נשמר עותק מקומי חלופי.");
  }
}

function loadAccessibilityPreferences() {
  try {
    const saved = JSON.parse(localStorage.getItem(ACCESSIBILITY_STORAGE_KEY));
    return { fontScale: 1, highContrast: false, underlineLinks: false, ...saved };
  } catch {
    return { fontScale: 1, highContrast: false, underlineLinks: false };
  }
}

function saveState(action) {
  if (action) {
    state.auditLog.unshift({
      id: crypto.randomUUID(),
      action,
      at: new Date().toISOString(),
    });
  }
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(state));
  } catch {
    // IndexedDB remains the primary storage if localStorage is unavailable.
  }
  void persistStateToDatabase(structuredClone(state));
  window.clearTimeout(storageStatusTimer);
  storageStatusTimer = window.setTimeout(() => void updateStorageStatus(), 350);
}

